import { Badge, Tooltip } from "@mantine/core";
import { IconRobot, IconRuler2 } from "@tabler/icons-react";

/** Always tells the user whether output came from a real AI model or the rule-based demo provider. */
export function AISourceBadge({ isMock, model }: { isMock: boolean; model?: string | null }) {
  if (isMock) {
    return (
      <Tooltip label="No AI provider is configured. This output was produced by local rules and templates, not by a language model.">
        <Badge color="orange" variant="light" leftSection={<IconRuler2 size={12} />} tt="none">
          Demo · rule-based (not AI)
        </Badge>
      </Tooltip>
    );
  }
  return (
    <Tooltip label="Generated by an external AI model from a redacted copy of your resume. Review before using.">
      <Badge color="violet" variant="light" leftSection={<IconRobot size={12} />} tt="none">
        AI-generated{model ? ` · ${model}` : ""}
      </Badge>
    </Tooltip>
  );
}
